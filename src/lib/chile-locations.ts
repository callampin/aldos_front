/** Isla de Pascua (Rapa Nui) requiere logística especial de despacho. */
export const ISLA_DE_PASCUA = {
  regionCode: 'V',
  comuna: 'Isla de Pascua',
} as const;

const REGIONS_BY_CODE: Map<string, Region> = new Map(
  REGIONS.map((region) => [region.code, region]),
);

/** Obtiene una región por su código (`RM`, `V`, ...). */
export function getRegion(code: string): Region | undefined {
  return REGIONS_BY_CODE.get(code);
}

/** Lista las comunas de una región (vacío si el código no existe). */
export function getComunas(code: string): readonly string[] {
  return REGIONS_BY_CODE.get(code)?.comunas ?? [];
}

/** Verifica que una comuna pertenezca a la región indicada. */
export function isValidComuna(code: string, comuna: string): boolean {
  return getComunas(code).includes(comuna);
}

/** Opciones `{ value, label }` para un `<select>` de regiones. */
export function regionOptions(): Array<{ value: string; label: string }> {
  return REGIONS.map((region) => ({ value: region.code, label: region.name }));
}

/** Busca a qué región pertenece una comuna. */
export function findRegionByComuna(comuna: string): Region | undefined {
  return REGIONS.find((region) => region.comunas.includes(comuna));
}

/** Indica si el par región/comuna corresponde a Isla de Pascua. */
export function isIslaDePascua(code: string, comuna: string): boolean {
  return code === ISLA_DE_PASCUA.regionCode && comuna === ISLA_DE_PASCUA.comuna;
}
